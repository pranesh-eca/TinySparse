import numpy as np

def generate_header():
    print("=== Step 4: Compiling Quantized Weights to C++ Header ===")
    
    data = np.load("pruned_quantized_model.npz")
    fc1_w = data["fc1"]       # Shape: (32, 128)
    fc1_b = data["fc1_bias"]  # Shape: (32,)
    fc2_w = data["fc2"]       # Shape: (16, 32)
    fc2_b = data["fc2_bias"]  # Shape: (16,)
    fc3_w = data["fc3"]       # Shape: (4, 16) - Dense
    fc3_b = data["fc3_bias"]  # Shape: (4,)

    header = []
    header.append("// =============================================================================")
    header.append("// Auto-generated by TinySparse Compiler - Do NOT Edit Directly")
    header.append("// Target: Generic 32-bit MCUs (ARM Cortex-M, ESP32, RISC-V)")
    header.append("// Format: Pure 1D Sparse INT8 COO (Values + Column Indices)")
    header.append("// =============================================================================\n")
    header.append("#pragma once")
    header.append("#include <stdint.h>\n")

    # -------------------------------------------------------------------------
    # Helper: Export a Layer as 1D Sparse Neurons
    # -------------------------------------------------------------------------
    def export_sparse_layer(weights, biases, layer_name):
        num_neurons, input_dim = weights.shape
        header.append(f"// --- Layer: {layer_name} (Inputs: {input_dim}, Neurons: {num_neurons}) ---")
        header.append(f"#define {layer_name.upper()}_NUM_NEURONS {num_neurons}")
        header.append(f"#define {layer_name.upper()}_INPUT_DIM {input_dim}\n")

        all_values = []
        all_indices = []
        neuron_nnz = []
        neuron_offsets = [0]

        total_nnz = 0
        for neuron_idx in range(num_neurons):
            row = weights[neuron_idx, :]
            nz_cols = np.nonzero(row)[0]
            nz_vals = row[nz_cols]
            
            nnz = len(nz_vals)
            neuron_nnz.append(nnz)
            total_nnz += nnz
            neuron_offsets.append(total_nnz)

            all_values.extend(nz_vals)
            all_indices.extend(nz_cols)

        # uint8_t indices suffice since input_dim <= 256
        header.append(f"#define {layer_name.upper()}_TOTAL_NNZ {total_nnz}")
        header.append(f"const int8_t  {layer_name}_values[{total_nnz}] = {{\n    " + ", ".join(map(str, all_values)) + "\n};")
        header.append(f"const uint8_t {layer_name}_indices[{total_nnz}] = {{\n    " + ", ".join(map(str, all_indices)) + "\n};")
        header.append(f"const uint16_t {layer_name}_offsets[{num_neurons + 1}] = {{\n    " + ", ".join(map(str, neuron_offsets)) + "\n};")
        
        # Scale biases to integer scale matching INT8 inputs
        int_biases = np.round(biases * 127.0).astype(np.int32)
        header.append(f"const int32_t {layer_name}_biases[{num_neurons}] = {{\n    " + ", ".join(map(str, int_biases)) + "\n};\n")

    # -------------------------------------------------------------------------
    # Helper: Export Dense Layer (fc3)
    # -------------------------------------------------------------------------
    def export_dense_layer(weights, biases, layer_name):
        num_neurons, input_dim = weights.shape
        header.append(f"// --- Layer: {layer_name} (Dense Fallback to Prevent Index Tax) ---")
        header.append(f"#define {layer_name.upper()}_NUM_NEURONS {num_neurons}")
        header.append(f"#define {layer_name.upper()}_INPUT_DIM {input_dim}")
        
        flat_w = weights.flatten()
        header.append(f"const int8_t {layer_name}_weights[{weights.size}] = {{\n    " + ", ".join(map(str, flat_w)) + "\n};")
        
        int_biases = np.round(biases * 127.0).astype(np.int32)
        header.append(f"const int32_t {layer_name}_biases[{num_neurons}] = {{\n    " + ", ".join(map(str, int_biases)) + "\n};\n")

    # Export layers
    export_sparse_layer(fc1_w, fc1_b, "fc1")
    export_sparse_layer(fc2_w, fc2_b, "fc2")
    export_dense_layer(fc3_w, fc3_b, "fc3")

    with open("model_weights.h", "w") as f:
        f.write("\n".join(header))

    print("[v] Generated 'model_weights.h' successfully.")
    print("    - fc1: 1D Sparse COO layout")
    print("    - fc2: 1D Sparse COO layout")
    print("    - fc3: Dense layout (zero overhead)")

if __name__ == "__main__":
    generate_header()