import os
import numpy as np

def dense_to_coo(weight_matrix):
    """Converts a 2D INT8 weight matrix (Out x In) into COO format arrays."""
    values = []
    col_indices = []
    row_offsets = [0]

    for row in weight_matrix:
        non_zero_cols = np.nonzero(row)[0]
        for col in non_zero_cols:
            values.append(int(row[col]))
            col_indices.append(int(col))
        row_offsets.append(len(values))

    return (
        np.array(values, dtype=np.int8),
        np.array(col_indices, dtype=np.uint8),
        np.array(row_offsets, dtype=np.uint16)
    )

def format_c_array(arr, c_type, name, per_line=16):
    lines = [f"const {c_type} {name}[{len(arr)}] = {{"]
    for i in range(0, len(arr), per_line):
        chunk = ", ".join(str(x) for x in arr[i:i + per_line])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)

def compile_model():
    print("=" * 70)
    print(" TinySparse C++ Header Compiler (COO + Bit-Exact Reference Vectors)")
    print("=" * 70)

    npz_path = os.path.join("models", "pruned_quantized_model.npz")
    if not os.path.exists(npz_path):
        raise FileNotFoundError(f"Missing {npz_path}. Run prune_and_quantize.py first.")

    data = np.load(npz_path)
    fc1_w, fc1_b, fc1_s = data["fc1_w"], data["fc1_b"], int(data["fc1_shift"])
    fc2_w, fc2_b, fc2_s = data["fc2_w"], data["fc2_b"], int(data["fc2_shift"])
    fc3_w, fc3_b        = data["fc3_w"], data["fc3_b"]

    ref_input  = data["ref_input"]
    ref_l1     = data["ref_l1"]
    ref_l2     = data["ref_l2"]
    ref_logits = data["ref_logits"]
    ref_label  = int(data["ref_label"])

    fc1_val, fc1_idx, fc1_off = dense_to_coo(fc1_w)
    fc2_val, fc2_idx, fc2_off = dense_to_coo(fc2_w)
    fc3_flat = fc3_w.ravel()

    # Exact Flash Accounting (in Bytes)
    l1_sparse_bytes = len(fc1_val) * 1 + len(fc1_idx) * 1 + len(fc1_off) * 2 + len(fc1_b) * 4
    l1_dense_bytes  = fc1_w.size * 1 + len(fc1_b) * 4
    l2_sparse_bytes = len(fc2_val) * 1 + len(fc2_idx) * 1 + len(fc2_off) * 2 + len(fc2_b) * 4
    l3_dense_bytes  = len(fc3_flat) * 1 + len(fc3_b) * 4
    total_sparse_model_bytes = l1_sparse_bytes + l2_sparse_bytes + l3_dense_bytes
    total_dense_model_bytes  = l1_dense_bytes + (fc2_w.size + len(fc2_b) * 4) + l3_dense_bytes

    header_lines = [
        "#ifndef MODEL_WEIGHTS_H",
        "#define MODEL_WEIGHTS_H",
        "",
        "#include <stdint.h>",
        "",
        "// Automatically generated by tinysparse_compiler.py",
        f"// Layer 1 Non-Zero MACs: {len(fc1_val)} / {fc1_w.size}",
        f"// Layer 2 Non-Zero MACs: {len(fc2_val)} / {fc2_w.size}",
        f"// Total Model Flash (Sparse COO): {total_sparse_model_bytes} Bytes (vs {total_dense_model_bytes} Bytes Dense)",
        "",
        f"#define FC1_OUT_DIM {fc1_w.shape[0]}",
        f"#define FC1_SHIFT   {fc1_s}",
        f"#define FC2_OUT_DIM {fc2_w.shape[0]}",
        f"#define FC2_SHIFT   {fc2_s}",
        f"#define FC3_IN_DIM  {fc3_w.shape[1]}",
        f"#define FC3_OUT_DIM {fc3_w.shape[0]}",
        "",
        "// --- Layer 1 Sparse COO Parameters ---",
        format_c_array(fc1_val, "int8_t",   "fc1_values"),
        format_c_array(fc1_idx, "uint8_t",  "fc1_col_indices"),
        format_c_array(fc1_off, "uint16_t", "fc1_row_offsets"),
        format_c_array(fc1_b,   "int32_t",  "fc1_bias"),
        "",
        "// --- Layer 2 Sparse COO Parameters ---",
        format_c_array(fc2_val, "int8_t",   "fc2_values"),
        format_c_array(fc2_idx, "uint8_t",  "fc2_col_indices"),
        format_c_array(fc2_off, "uint16_t", "fc2_row_offsets"),
        format_c_array(fc2_b,   "int32_t",  "fc2_bias"),
        "",
        "// --- Layer 3 Dense Parameters ---",
        format_c_array(fc3_flat, "int8_t",  "fc3_weights_dense"),
        format_c_array(fc3_b,    "int32_t", "fc3_bias"),
        "",
        "// --- Golden Reference Vectors for Bit-Exact Verification ---",
        f"#define GOLDEN_EXPECTED_CLASS {ref_label}",
        format_c_array(ref_input,  "int8_t",  "golden_input"),
        format_c_array(ref_l1,     "int8_t",  "golden_l1_out"),
        format_c_array(ref_l2,     "int8_t",  "golden_l2_out"),
        format_c_array(ref_logits, "int32_t", "golden_logits"),
        "",
        "#endif // MODEL_WEIGHTS_H",
        ""
    ]

    out_path = os.path.join("include", "model_weights.h")
    with open(out_path, "w") as f:
        f.write("\n".join(header_lines))

    print(f"Exported C++ header to: {out_path}")
    print(f"  L1 Flash (Val+Idx+Off+Bias) : {l1_sparse_bytes} B (Dense: {l1_dense_bytes} B)")
    print(f"  L2 Flash (Val+Idx+Off+Bias) : {l2_sparse_bytes} B")
    print(f"  L3 Flash (Dense+Bias)       : {l3_dense_bytes} B")
    print(f"  Total Model Flash Footprint : {total_sparse_model_bytes} Bytes (Saved {100.0*(1 - total_sparse_model_bytes/total_dense_model_bytes):.1f}% overall)")
    print("=" * 70)

if __name__ == "__main__":
    compile_model()